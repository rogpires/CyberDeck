#!/usr/bin/env python3
"""Converts TentacleOS's RGBA PNG icon frames into main/icons.h alpha masks.

Reads the alpha channel of each PNG, scales it (preserving aspect) into a
MASTER x MASTER box and centres it, so our hand-rolled renderer can draw the
exact same icon shapes.
"""
import os
import struct
import sys
import zlib

MASTER = 96
BOX = 82  # icon fills this, centred in MASTER

SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    "/private/tmp/claude-502/-Users-rogeriopires-Documents-Github-CyberDeck/"
    "3e2befa4-bc32-4afa-9d33-2f25f95c757b/scratchpad/TentacleOS/firmware_p4/assets/frames")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# our icon name -> their PNG file
MAP = [
    ("wifi", "wifi_frame_0.png"),
    ("bluetooth", "ble_frame_0.png"),
    ("nfc", "nfc_frame_0.png"),
    ("subghz", "subghz_frame_0.png"),
    ("lora", "lora_frame_0.png"),
    ("rfid", "rfid_frame_0.png"),
    ("ir", "ir_frame_0.png"),
    ("usb", "usb_frame_0.png"),
    ("folder", "folder_frame_0.png"),
    ("file", "file_frame_0.png"),
    ("gear", "config_frame_0.png"),
    ("apps", "apps_frame_0.png"),
    ("gpios", "gpios_frame_0.png"),
    ("card", "card_frame_0.png"),
]


def load_png_alpha(path):
    data = open(path, "rb").read()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a png"
    pos = 8
    width = height = bit_depth = color_type = 0
    idat = b""
    while pos < len(data):
        length = struct.unpack(">I", data[pos:pos + 4])[0]
        ctype = data[pos + 4:pos + 8]
        chunk = data[pos + 8:pos + 8 + length]
        if ctype == b"IHDR":
            width, height, bit_depth, color_type = struct.unpack(">IIBB", chunk[:10])
        elif ctype == b"IDAT":
            idat += chunk
        elif ctype == b"IEND":
            break
        pos += 12 + length
    assert bit_depth == 8 and color_type == 6, f"need 8-bit RGBA, got depth {bit_depth} type {color_type}"

    raw = zlib.decompress(idat)
    stride = width * 4
    alpha = [[0] * width for _ in range(height)]
    prev = bytearray(stride)
    p = 0
    for y in range(height):
        f = raw[p]
        p += 1
        line = bytearray(raw[p:p + stride])
        p += stride
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b = prev[i]
            c = prev[i - 4] if i >= 4 else 0
            if f == 1:
                line[i] = (line[i] + a) & 0xFF
            elif f == 2:
                line[i] = (line[i] + b) & 0xFF
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 0xFF
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pr = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[i] = (line[i] + pr) & 0xFF
        for x in range(width):
            alpha[y][x] = line[x * 4 + 3]
        prev = line
    return width, height, alpha


def sample(alpha, w, h, fx, fy):
    x0 = int(fx); y0 = int(fy)
    x1 = min(x0 + 1, w - 1); y1 = min(y0 + 1, h - 1)
    dx = fx - x0; dy = fy - y0
    top = alpha[y0][x0] * (1 - dx) + alpha[y0][x1] * dx
    bot = alpha[y1][x0] * (1 - dx) + alpha[y1][x1] * dx
    return int(top * (1 - dy) + bot * dy)


def to_master(path):
    w, h, alpha = load_png_alpha(path)
    scale = BOX / max(w, h)
    dw, dh = int(w * scale), int(h * scale)
    ox, oy = (MASTER - dw) // 2, (MASTER - dh) // 2
    out = bytearray(MASTER * MASTER)
    for y in range(dh):
        for x in range(dw):
            out[(oy + y) * MASTER + ox + x] = sample(alpha, w, h, x / scale, y / scale)
    return out


# Classic 11x8 space-invader, as a procedural icon (no PNG source)
INVADER = [
    "..X.....X..",
    "...X...X...",
    "..XXXXXXX..",
    ".XX.XXX.XX.",
    "XXXXXXXXXXX",
    "X.XXXXXXX.X",
    "X.X.....X.X",
    "...XX.XX...",
]

def invader_master():
    gw, gh = len(INVADER[0]), len(INVADER)
    cell = MASTER * 72 // 100 // gw          # fill ~72% of the icon
    ox = (MASTER - cell * gw) // 2
    oy = (MASTER - cell * gh) // 2
    out = bytearray(MASTER * MASTER)
    for ry in range(gh):
        for rx in range(gw):
            if INVADER[ry][rx] != 'X':
                continue
            for dy in range(cell):
                for dx in range(cell):
                    out[(oy + ry * cell + dy) * MASTER + ox + rx * cell + dx] = 255
    return bytes(out)


def main():
    out = ["// Generated by tools/png2icons.py from TentacleOS PNG frames (github.com/HighCodeh/TentacleOS).",
           "// Anti-aliased alpha masks, MASTER x MASTER, 1 byte each.",
           "#pragma once", "#include <stdint.h>", "",
           f"#define ICON_SIZE {MASTER}", "",
           "typedef struct {", "    const char* name;", "    const uint8_t* alpha;", "} Icon;", ""]
    available = []
    for name, filename in MAP:
        path = os.path.join(SRC, filename)
        if not os.path.exists(path):
            print("skip (missing):", filename)
            continue
        alpha = to_master(path)
        available.append(name)
        out.append(f"static const uint8_t {name}_alpha[{MASTER * MASTER}] = {{")
        for i in range(0, len(alpha), 24):
            out.append("    " + ",".join(str(v) for v in alpha[i:i + 24]) + ",")
        out += ["};", ""]
    game = invader_master()
    available.append("game")
    out.append(f"static const uint8_t game_alpha[{MASTER * MASTER}] = {{")
    for i in range(0, len(game), 24):
        out.append("    " + ",".join(str(v) for v in game[i:i + 24]) + ",")
    out += ["};", ""]

    out.append("static const Icon icons[] = {")
    for name in available:
        out.append(f'    {{"{name}", {name}_alpha}},')
    out += ["};", "#define ICON_COUNT (sizeof(icons) / sizeof(icons[0]))"]
    open(os.path.join(ROOT, "main", "icons.h"), "w").write("\n".join(out) + "\n")

    # ASCII preview
    shades = " .:-=+*#%@"
    for name in ("wifi", "bluetooth", "nfc", "lora"):
        if name not in available:
            continue
        alpha = to_master(os.path.join(SRC, dict(MAP)[name]))
        print(name)
        for y in range(0, MASTER, 4):
            print("".join(shades[alpha[y * MASTER + x] * (len(shades) - 1) // 255] for x in range(0, MASTER, 2)))
        print()


main()
