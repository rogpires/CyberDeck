#!/usr/bin/env python3
"""Converts the Spleen BDF fonts in fonts/ into main/fonts.h

Every font gets the same glyph set (see CODEPOINTS), so a cell stores a glyph index that is valid for all fonts.
Glyphs a font lacks are replaced by a look-alike: box drawing becomes + - |, accented letters their base letter.
"""
import os
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = ["spleen-5x8", "spleen-6x12", "spleen-8x16", "spleen-12x24"]

CODEPOINTS = (
    list(range(0x20, 0x7F))          # ASCII: glyph index = c - 0x20
    + list(range(0xA0, 0x100))       # Latin-1: accents
    + list(range(0x2500, 0x2580))    # box drawing
    + list(range(0x2580, 0x25A0))    # block elements
    + [0x2190, 0x2191, 0x2192, 0x2193, 0x2022, 0x2026, 0x25B2, 0x25B6, 0x25BC, 0x25C0, 0x25CF, 0x25CB, 0x2713, 0x2717]
)


def parse_bdf(path):
    glyphs, ascent = {}, 0
    width = height = 0
    lines = iter(open(path, encoding="latin-1").read().splitlines())
    for line in lines:
        if line.startswith("FONTBOUNDINGBOX"):
            width, height = map(int, line.split()[1:3])
        elif line.startswith("FONT_ASCENT"):
            ascent = int(line.split()[1])
        elif line.startswith("ENCODING"):
            code = int(line.split()[1])
        elif line.startswith("BBX"):
            bw, bh, bx, by = map(int, line.split()[1:5])
        elif line == "BITMAP":
            rows = [0] * height
            for y in range(bh):
                bits = int(next(lines), 16)
                nbits = ((bw + 7) // 8) * 8
                row = ascent - (by + bh) + y
                for x in range(bw):
                    if bits & (1 << (nbits - 1 - x)) and 0 <= row < height and 0 <= bx + x < width:
                        rows[row] |= 0x8000 >> (bx + x)
            glyphs[code] = rows
    return width, height, glyphs


SYMBOL_FALLBACKS = {0x2190: "<", 0x2191: "^", 0x2192: ">", 0x2193: "v", 0x2022: "*", 0x2026: ".",
                    0x25B2: "^", 0x25B6: ">", 0x25BC: "v", 0x25C0: "<", 0x25CF: "*", 0x25CB: "o",
                    0x2713: "v", 0x2717: "x"}


def fallback(code):
    name = unicodedata.name(chr(code), "")
    if name.startswith("BOX DRAWINGS"):
        if "VERTICAL" in name and "HORIZONTAL" not in name and " AND " not in name:
            return ord("|")
        if ("HORIZONTAL" in name or "DASH" in name) and "VERTICAL" not in name and " AND " not in name:
            return ord("-")
        return ord("+")
    if 0x2580 <= code < 0x25A0:
        return ord("#")
    if code in SYMBOL_FALLBACKS:
        return ord(SYMBOL_FALLBACKS[code])
    base = unicodedata.normalize("NFD", chr(code))[0]
    if base.isascii() and base.isprintable() and base != chr(code):
        return ord(base)
    return ord("?")


def main():
    out = ["// Generated by tools/gen_fonts.py from the Spleen fonts (fonts/LICENSE-spleen, BSD 2-Clause).",
           "// Each glyph row is 16 bits, the leftmost pixel in bit 15. Glyph indexes are shared by all fonts.",
           "#pragma once", "#include <stdint.h>", "",
           "typedef struct {", "    const char* name;", "    uint8_t width;", "    uint8_t height;",
           "    const uint16_t* rows; // [glyph * height + y]", "} Font;", "",
           f"#define GLYPH_COUNT {len(CODEPOINTS)}",
           "#define GLYPH_UNKNOWN ('?' - 0x20)", "",
           "// Sorted: the glyph index of a code point is its position (ASCII c is c - 0x20)",
           "static const uint16_t glyph_codepoints[GLYPH_COUNT] = {"]
    for i in range(0, len(CODEPOINTS), 12):
        out.append("    " + ", ".join(f"0x{c:04x}" for c in CODEPOINTS[i:i + 12]) + ",")
    out += ["};", ""]

    entries = []
    for name in FONTS:
        width, height, glyphs = parse_bdf(os.path.join(ROOT, "fonts", name + ".bdf"))
        ident = name.replace("-", "_")
        missing = 0
        out.append(f"static const uint16_t {ident}_rows[] = {{")
        for code in CODEPOINTS:
            rows = glyphs.get(code)
            if rows is None:
                missing += 1
                rows = glyphs.get(fallback(code), [0] * height)
            out.append("    " + ", ".join(f"0x{r:04x}" for r in rows) + f", // U+{code:04X}")
        out += ["};", ""]
        entries.append(f'    {{"{width}x{height}", {width}, {height}, {ident}_rows}},')
        print(f"{name}: {len(CODEPOINTS) - missing}/{len(CODEPOINTS)} glyphs, {missing} replaced")
    out.append("static const Font fonts[] = {")
    out.extend(entries)
    out += ["};", "#define FONT_COUNT (sizeof(fonts) / sizeof(fonts[0]))"]
    open(os.path.join(ROOT, "main", "fonts.h"), "w").write("\n".join(out) + "\n")


main()
